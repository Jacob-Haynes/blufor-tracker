"""BT-2: OTS's CoT port is set to 8087 on every install, idempotently, and bridge.check names
the OTS-still-on-8088 case."""

import os
import socket
import stat
import subprocess
from pathlib import Path

from bridge import check

DEPLOY = Path(__file__).resolve().parent.parent / "deploy"
SCRIPT = DEPLOY / "ots_port.sh"

OTS_CONFIG = """# generated by flask ots generate-config
OTS_LISTENER_PORT: 8081
OTS_TCP_STREAMING_PORT: 8088
OTS_SSL_STREAMING_PORT: 8089
SECRET_KEY: abc
"""


def run(cfg, port="8087"):
    return subprocess.run(["bash", str(SCRIPT), str(cfg), port], capture_output=True, text=True)


def backups(cfg):
    return sorted(cfg.parent.glob(cfg.name + ".bak-*"))


def test_changes_8088_to_8087_with_backup_and_keeps_mode(tmp_path):
    cfg = tmp_path / "config.yml"
    cfg.write_text(OTS_CONFIG)
    os.chmod(cfg, 0o600)
    p = run(cfg)
    assert p.returncode == 2, p.stderr
    assert "changed OTS_TCP_STREAMING_PORT from 8088 to 8087" in p.stdout
    text = cfg.read_text()
    assert "OTS_TCP_STREAMING_PORT: 8087\n" in text and "8088" not in text
    assert "OTS_SSL_STREAMING_PORT: 8089" in text and "SECRET_KEY: abc" in text
    assert stat.S_IMODE(cfg.stat().st_mode) == 0o600
    (b,) = backups(cfg)
    assert b.read_text() == OTS_CONFIG


def test_second_run_is_a_no_op(tmp_path):
    cfg = tmp_path / "config.yml"
    cfg.write_text(OTS_CONFIG)
    run(cfg)
    before = cfg.read_text()
    p = run(cfg)
    assert p.returncode == 0 and "already 8087" in p.stdout and "no change" in p.stdout
    assert cfg.read_text() == before and len(backups(cfg)) == 1


def test_missing_key_is_added(tmp_path):
    cfg = tmp_path / "config.yml"
    cfg.write_text("SECRET_KEY: abc")  # no trailing newline
    p = run(cfg)
    assert p.returncode == 2 and "was not set" in p.stdout
    assert cfg.read_text() == "SECRET_KEY: abc\nOTS_TCP_STREAMING_PORT: 8087\n"


def test_quoted_value_with_comment_counts_as_set(tmp_path):
    cfg = tmp_path / "config.yml"
    cfg.write_text("OTS_TCP_STREAMING_PORT: '8087'  # kit port\n")
    assert run(cfg).returncode == 0


def test_duplicates_collapsed(tmp_path):
    cfg = tmp_path / "config.yml"
    cfg.write_text("OTS_TCP_STREAMING_PORT: 8087\nX: 1\nOTS_TCP_STREAMING_PORT: 8088\n")
    p = run(cfg)
    assert p.returncode == 2 and "duplicate" in p.stdout
    assert cfg.read_text() == "OTS_TCP_STREAMING_PORT: 8087\nX: 1\nOTS_TCP_STREAMING_PORT: 8087\n"


def test_missing_config_is_reported_not_created(tmp_path):
    cfg = tmp_path / "ots" / "config.yml"
    p = run(cfg)
    assert p.returncode == 1 and "not found" in p.stderr and not cfg.exists()


def test_install_runs_the_port_step_whether_or_not_ots_was_installed():
    text = (DEPLOY / "install.sh").read_text()
    branch_end = text.index("OTS_JUST_INSTALLED=1\nfi\n")
    call = text.index('ots_port.sh" "$OTS_CONFIG" 8087')
    assert call > branch_end  # after the if/else, so it always runs
    assert "systemctl is-active --quiet" in text[call:call + 800]


def _free_port():
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


def test_check_names_ots_on_8088(monkeypatch):
    srv = socket.socket()
    srv.bind(("127.0.0.1", 0))
    srv.listen(5)
    monkeypatch.setattr(check, "OTS_DEFAULT_TCP_PORT", srv.getsockname()[1])
    try:
        ok, msg = check.check_tak("127.0.0.1", _free_port())
    finally:
        srv.close()
    assert not ok and "nothing listening on TAK_PORT" in msg and "OTS may be on" in msg


def test_check_when_nothing_listens_at_all(monkeypatch):
    monkeypatch.setattr(check, "OTS_DEFAULT_TCP_PORT", _free_port())
    ok, msg = check.check_tak("127.0.0.1", _free_port())
    assert not ok and "nothing listening on TAK_PORT" in msg and "Is opentakserver running" in msg
